#!/usr/bin/env python3
"""Rebuilds the firmware header for the wake word model from the files in model/.

    python3 make_model_header.py                       # writes model/hey_dewy_model.h
    python3 make_model_header.py ../../firmware/dewy/hey_dewy_model.h

The settings (cutoff, window, working memory) come from model/hey_dewy.json, so changing them there and running
this again is enough: no need to train again.
"""
import json, sys
from pathlib import Path

here = Path(__file__).resolve().parent / "model"
out = Path(sys.argv[1]) if len(sys.argv) > 1 else here / "hey_dewy_model.h"
cfg = json.loads((here / "hey_dewy.json").read_text())
data = (here / "stream_state_internal_quant.tflite").read_bytes()
assert len(data) == cfg["model_bytes"], "the .tflite and the .json don't belong together"

lines = ["// Hey Dewy wake word model, trained with microWakeWord. Generated by voice/wakeword/make_model_header.py.",
         "#pragma once", "#include <stdint.h>",
         f"#define HEY_DEWY_PROBABILITY_CUTOFF {cfg['probability_cutoff']}f",
         f"#define HEY_DEWY_SLIDING_WINDOW {cfg['sliding_window_size']}",
         f"#define HEY_DEWY_TENSOR_ARENA {cfg['tensor_arena_size']}",
         f"static const unsigned int HEY_DEWY_MODEL_LEN = {len(data)};",
         "alignas(16) static const uint8_t HEY_DEWY_MODEL[] = {"]
for i in range(0, len(data), 16):
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({len(data)} bytes of model)")
